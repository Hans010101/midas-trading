_HK_CODE_LEN = 5


def normalize_hk_code(code: str) -> str:
    """规范成 5 位港股代码:`700` / `0700` / `00700` / `00700.HK` → `00700`。

    阶段三下单 / 阶段一查 lot 都先过这个,容错任意位数 + .HK 后缀(对齐 ADR 0034a §2.4)。
    """
    c = code.strip().upper()
    if c.endswith(".HK"):
        c = c[:-3]
    c = c.lstrip("0") or "0"  # 去前导零再补,容错 '700' / '0700' / '00700'
    return c.zfill(_HK_CODE_LEN)


HK_POOL_SYMBOLS: tuple[str, ...] = tuple(sym for sym, _, _, _ in HK_POOL)
HK_POOL_META: dict[str, tuple[str, str]] = {
    sym: (name, sector) for sym, name, _, sector in HK_POOL
}
# 每手股数(★种子值 · 待核 HKEX)· 规范化代码 → lot
HK_LOT_SIZE: dict[str, int] = {sym: lot for sym, _, lot, _ in HK_POOL}


def hk_lot_size(code: str) -> int | None:
    """查每手股数(★种子值 · 待核 HKEX)。

    不在策展池 → `None`(阶段三下单时表示「该标的暂不可下单」· 决策②兜底)。
    """
    return HK_LOT_SIZE.get(normalize_hk_code(code))
